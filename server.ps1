<#
.SYNOPSIS
    Dabnaps Full-Stack Local Web & API Server (Zero External Dependencies)
.DESCRIPTION
    Serves the Dabnaps Online Storefront, Admin Inventory & R&D Dashboard, and REST API
    endpoints backed directly by data\inventory.json (and auto-syncs data\inventory-sync.js).
#>

param(
    [int]$Port = 8080
)

$ErrorActionPreference = "Stop"
$WorkspaceRoot = $PSScriptRoot
$JsonPath = Join-Path $WorkspaceRoot "data\inventory.json"
$SyncJsPath = Join-Path $WorkspaceRoot "data\inventory-sync.js"

function Sync-InventoryFiles {
    param($DbObject)
    $Timestamp = (Get-Date).ToString("yyyy-MM-ddTHH:mm:sszzz")
    if ($DbObject.company) {
        $DbObject.company.lastUpdated = $Timestamp
    }
    $JsonText = $DbObject | ConvertTo-Json -Depth 10
    Set-Content -Path $JsonPath -Value $JsonText -Encoding UTF8
    $SyncContent = "// Auto-generated by Dabnaps Server ($Timestamp)`nwindow.DABNAPS_INITIAL_DATA = $JsonText;`n"
    Set-Content -Path $SyncJsPath -Value $SyncContent -Encoding UTF8
}

$Listener = New-Object System.Net.HttpListener
$Prefix = "http://localhost:$Port/"
$Listener.Prefixes.Add($Prefix)
$Listener.Start()

Write-Host "======================================================" -ForegroundColor Cyan
Write-Host "  DABNAPS ONLINE STORE & INVENTORY SERVER RUNNING" -ForegroundColor Green
Write-Host "  Storefront & Admin URL : $Prefix" -ForegroundColor Yellow
Write-Host "  Live Database          : $JsonPath" -ForegroundColor Gray
Write-Host "  Press Ctrl+C to stop the server." -ForegroundColor Gray
Write-Host "======================================================" -ForegroundColor Cyan

$MimeTypes = @{
    ".html" = "text/html; charset=utf-8"
    ".css"  = "text/css; charset=utf-8"
    ".js"   = "application/javascript; charset=utf-8"
    ".json" = "application/json; charset=utf-8"
    ".png"  = "image/png"
    ".jpg"  = "image/jpeg"
    ".jpeg" = "image/jpeg"
    ".svg"  = "image/svg+xml"
    ".ico"  = "image/x-icon"
}

try {
    while ($Listener.IsListening) {
        try {
            $Context = $Listener.GetContext()
        } catch {
            if (-not $Listener.IsListening) { break }
            continue
        }

        try {
            $Request = $Context.Request
            $Response = $Context.Response
        $Response.Headers.Add("Access-Control-Allow-Origin", "*")
        $Response.Headers.Add("Access-Control-Allow-Methods", "GET, POST, PUT, OPTIONS")
        $Response.Headers.Add("Access-Control-Allow-Headers", "Content-Type, X-Admin-Passcode, Authorization")

        if ($Request.HttpMethod -eq "OPTIONS") {
            $Response.StatusCode = 200
            $Response.Close()
            continue
        }

        $UrlPath = $Request.Url.LocalPath

        $AdminPasscode = if ($env:DABNAPS_ADMIN_PASSCODE) { $env:DABNAPS_ADMIN_PASSCODE } else { "Dabnaps2026!" }
        $ProvidedPasscode = $null
        $AdminHeader = $Request.Headers["X-Admin-Passcode"]
        if (-not [string]::IsNullOrWhiteSpace($AdminHeader)) {
            $ProvidedPasscode = $AdminHeader.Trim()
        } else {
            $AuthHeader = $Request.Headers["Authorization"]
            if (-not [string]::IsNullOrWhiteSpace($AuthHeader)) {
                if ($AuthHeader -match '^Bearer\s+(.*)$') {
                    $ProvidedPasscode = $Matches[1].Trim()
                } else {
                    $ProvidedPasscode = $AuthHeader.Trim()
                }
            }
        }
        $HasAuth = ($null -ne $ProvidedPasscode -and $ProvidedPasscode -ne "")
        $IsAuth = ($HasAuth -and $ProvidedPasscode -eq $AdminPasscode)

        # API Route: GET /api/inventory or /api.php
        if (($UrlPath -eq "/api/inventory" -or $UrlPath -eq "/api.php") -and $Request.HttpMethod -eq "GET") {
            $RequiresAdmin = ($Request.QueryString["scope"] -eq "admin" -or $Request.QueryString["cogs"] -ne $null)

            if ($HasAuth -and -not $IsAuth) {
                $Response.StatusCode = 403
                $ErrBytes = [System.Text.Encoding]::UTF8.GetBytes('{"error":"Forbidden: Invalid passcode"}')
                $Response.ContentType = "application/json; charset=utf-8"
                $Response.ContentLength64 = $ErrBytes.Length
                $Response.OutputStream.Write($ErrBytes, 0, $ErrBytes.Length)
                $Response.Close()
                continue
            }

            if ($RequiresAdmin -and -not $HasAuth) {
                $Response.StatusCode = 401
                $ErrBytes = [System.Text.Encoding]::UTF8.GetBytes('{"error":"Unauthorized: Admin passcode required"}')
                $Response.ContentType = "application/json; charset=utf-8"
                $Response.ContentLength64 = $ErrBytes.Length
                $Response.OutputStream.Write($ErrBytes, 0, $ErrBytes.Length)
                $Response.Close()
                continue
            }

            if ($IsAuth) {
                $RawJson = Get-Content -Path $JsonPath -Raw -Encoding UTF8
                $Bytes = [System.Text.Encoding]::UTF8.GetBytes($RawJson)
                $Response.ContentType = "application/json; charset=utf-8"
                $Response.ContentLength64 = $Bytes.Length
                $Response.OutputStream.Write($Bytes, 0, $Bytes.Length)
                $Response.Close()
                continue
            }

            # Public unauthenticated GET: sanitize COGS, orders, activityLog
            $RawJson = Get-Content -Path $JsonPath -Raw -Encoding UTF8
            $DbObj = $RawJson | ConvertFrom-Json
            if ($DbObj.products) {
                foreach ($prod in $DbObj.products) {
                    $prod.PSObject.Properties.Remove('cost')
                }
            }
            $DbObj.orders = @()
            $DbObj.activityLog = @()
            $SanitizedJson = $DbObj | ConvertTo-Json -Depth 10
            $Bytes = [System.Text.Encoding]::UTF8.GetBytes($SanitizedJson)
            $Response.ContentType = "application/json; charset=utf-8"
            $Response.ContentLength64 = $Bytes.Length
            $Response.OutputStream.Write($Bytes, 0, $Bytes.Length)
            $Response.Close()
            continue
        }

        # API Route: POST /api/inventory or /api.php (Save full or partial update from Admin or Checkout)
        if (($UrlPath -eq "/api/inventory" -or $UrlPath -eq "/api.php") -and $Request.HttpMethod -eq "POST") {
            if (-not $HasAuth) {
                $Response.StatusCode = 401
                $ErrBytes = [System.Text.Encoding]::UTF8.GetBytes('{"error":"Unauthorized: Admin passcode required"}')
                $Response.ContentType = "application/json; charset=utf-8"
                $Response.ContentLength64 = $ErrBytes.Length
                $Response.OutputStream.Write($ErrBytes, 0, $ErrBytes.Length)
                $Response.Close()
                continue
            }

            if (-not $IsAuth) {
                $Response.StatusCode = 403
                $ErrBytes = [System.Text.Encoding]::UTF8.GetBytes('{"error":"Forbidden: Invalid passcode"}')
                $Response.ContentType = "application/json; charset=utf-8"
                $Response.ContentLength64 = $ErrBytes.Length
                $Response.OutputStream.Write($ErrBytes, 0, $ErrBytes.Length)
                $Response.Close()
                continue
            }

            $Reader = New-Object System.IO.StreamReader($Request.InputStream, [System.Text.Encoding]::UTF8)
            $Body = $Reader.ReadToEnd()
            $Reader.Close()

            $UpdatedDb = $Body | ConvertFrom-Json
            Sync-InventoryFiles -DbObject $UpdatedDb

            $ReplyLastUpdated = if ($UpdatedDb.company -and $UpdatedDb.company.lastUpdated) { $UpdatedDb.company.lastUpdated } else { (Get-Date).ToString("yyyy-MM-ddTHH:mm:sszzz") }
            $Reply = @{ ok = $true; lastUpdated = $ReplyLastUpdated } | ConvertTo-Json
            $Bytes = [System.Text.Encoding]::UTF8.GetBytes($Reply)
            $Response.ContentType = "application/json; charset=utf-8"
            $Response.ContentLength64 = $Bytes.Length
            $Response.OutputStream.Write($Bytes, 0, $Bytes.Length)
            $Response.Close()
            continue
        }

        # Static File Serving
        if ($UrlPath -eq "/") { $UrlPath = "/index.html" }
        $RelativePath = $UrlPath.TrimStart('/').Replace('/', '\')
        $FilePath = Join-Path $WorkspaceRoot $RelativePath

        if (Test-Path $FilePath -PathType Leaf) {
            $Ext = [System.IO.Path]::GetExtension($FilePath).ToLower()
            $ContentType = if ($MimeTypes.ContainsKey($Ext)) { $MimeTypes[$Ext] } else { "application/octet-stream" }
            $FileBytes = [System.IO.File]::ReadAllBytes($FilePath)
            $Response.ContentType = $ContentType
            $Response.ContentLength64 = $FileBytes.Length
            $Response.OutputStream.Write($FileBytes, 0, $FileBytes.Length)
        } else {
            $Response.StatusCode = 404
            $NotFoundBytes = [System.Text.Encoding]::UTF8.GetBytes("404 Not Found: $UrlPath")
            $Response.OutputStream.Write($NotFoundBytes, 0, $NotFoundBytes.Length)
        }
        $Response.Close()
        } catch {
            # Client closed connection prematurely or I/O was aborted
            try { if ($Response) { $Response.Close() } } catch { }
        }
    }
} finally {
    $Listener.Stop()
}
