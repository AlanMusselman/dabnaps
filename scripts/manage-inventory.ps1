<#
.SYNOPSIS
    Dabnaps Inventory & Store Management CLI (Used by Antigravity AI Agent & Founders)
.DESCRIPTION
    Reads and modifies data\inventory.json and syncs data\inventory-sync.js so both the
    live Full-Stack Server and standalone file:// mode stay 100% in sync.
.EXAMPLE
    .\scripts\manage-inventory.ps1 -Action status
    .\scripts\manage-inventory.ps1 -Action low-stock
    .\scripts\manage-inventory.ps1 -Action restock -Sku "DN-SIL-MINI-AMB" -Delta 30 -Note "Moved Batch 2026-10B from post-cure oven to stock"
    .\scripts\manage-inventory.ps1 -Action set-price -Sku "DN-SIL-CL9-GLD" -Price 46.00
    .\scripts\manage-inventory.ps1 -Action update-rd -Sku "DN-SIL-STN-OBS" -Stage "Production Ready"
#>

param(
    [Parameter(Mandatory=$false)]
    [ValidateSet("status", "low-stock", "set-stock", "restock", "set-price", "update-rd", "add-product", "sync", "reconcile-batch")]
    [string]$Action = "status",

    [string]$Sku = "",
    [string]$BatchId = "",
    [int]$Stock = 0,
    [int]$Delta = 0,
    [double]$Price = 0,
    [double]$Cost = 0,
    [string]$Name = "",
    [string]$Category = "Silicone Mats",
    [string]$Stage = "",
    [string]$Colorway = "",
    [string]$Description = "",
    [string]$Note = ""
)

$ErrorActionPreference = "Stop"
$WorkspaceRoot = Split-Path -Parent $PSScriptRoot
$JsonPath = Join-Path $WorkspaceRoot "data\inventory.json"
$SyncJsPath = Join-Path $WorkspaceRoot "data\inventory-sync.js"

if (-not (Test-Path $JsonPath)) {
    Write-Error "Inventory database not found at $JsonPath"
}

$Db = Get-Content -Path $JsonPath -Raw -Encoding UTF8 | ConvertFrom-Json

function Save-Database {
    param([string]$LogMessage)
    $Timestamp = (Get-Date).ToString("yyyy-MM-ddTHH:mm:sszzz")
    $Db.company.lastUpdated = $Timestamp

    if ($LogMessage) {
        $NewLog = [PSCustomObject]@{
            timestamp = $Timestamp
            actor     = "Antigravity CLI"
            action    = $LogMessage
        }
        $Logs = @($NewLog) + @($Db.activityLog)
        if ($Logs.Count -gt 50) { $Logs = $Logs[0..49] }
        $Db.activityLog = $Logs
    }

    $JsonText = $Db | ConvertTo-Json -Depth 10
    Set-Content -Path $JsonPath -Value $JsonText -Encoding UTF8

    # Also write inventory-sync.js for zero-server fallback compatibility
    $SyncContent = "// Auto-generated by Dabnaps Inventory Manager ($Timestamp)`nwindow.DABNAPS_INITIAL_DATA = $JsonText;`n"
    Set-Content -Path $SyncJsPath -Value $SyncContent -Encoding UTF8
}

switch ($Action) {
    "status" {
        $TotalUnits = 0
        $TotalRetailValue = 0.0
        $TotalCostValue = 0.0
        $LowStockCount = 0

        Write-Host "`n=== DABNAPS INVENTORY & IN-HOUSE R&D REPORT ===" -ForegroundColor Cyan
        Write-Host ("Last Updated: {0}`n" -f $Db.company.lastUpdated) -ForegroundColor Gray

        $Table = foreach ($p in $Db.products) {
            $TotalUnits += $p.stock
            $TotalRetailValue += ($p.stock * $p.price)
            $TotalCostValue += ($p.stock * $p.cost)
            $IsLow = $p.stock -le $p.reorderPoint
            if ($IsLow) { $LowStockCount++ }

            [PSCustomObject]@{
                SKU        = $p.sku
                Name       = $p.name
                Category   = $p.category
                Stock      = $p.stock
                Alert      = if ($p.stock -eq 0) { "OUT OF STOCK" } elseif ($IsLow) { "LOW STOCK" } else { "OK" }
                Price      = ("`${0:N2}" -f $p.price)
                InHouse    = if ($p.inHouse) { "Yes ($($p.rdStage))" } else { "Partner" }
            }
        }
        $Table | Format-Table -AutoSize

        Write-Host ("Total Active SKUs : {0}" -f $Db.products.Count)
        Write-Host ("Total Units       : {0}" -f $TotalUnits)
        Write-Host ("Retail Valuation  : `${0:N2}" -f $TotalRetailValue) -ForegroundColor Green
        Write-Host ("Cost Valuation    : `${0:N2}" -f $TotalCostValue)
        Write-Host ("Low Stock Alerts  : {0}`n" -f $LowStockCount) -ForegroundColor ($(if ($LowStockCount -gt 0) { "Yellow" } else { "Green" }))

        if ($Db.inHouseProductionBatches) {
            Write-Host "=== IN-HOUSE PRODUCTION BATCHES ===" -ForegroundColor Cyan
            $BatchTable = foreach ($b in $Db.inHouseProductionBatches) {
                [PSCustomObject]@{
                    BatchID = $b.batchId
                    SKU     = $b.productSku
                    Name    = $b.productName
                    Passed  = ("{0}/{1}" -f $b.unitsPassedQC, $b.unitsPoured)
                    Stage   = $b.stage
                    Notes   = $b.notes
                }
            }
            $BatchTable | Format-Table -AutoSize
        }
    }

    "low-stock" {
        Write-Host "`n=== LOW STOCK & REORDER ALERTS ===" -ForegroundColor Yellow
        $LowItems = $Db.products | Where-Object { $_.stock -le $_.reorderPoint }
        if (-not $LowItems) {
            Write-Host "All SKUs are above their reorder points!" -ForegroundColor Green
        } else {
            $LowItems | Select-Object sku, name, stock, reorderPoint, rdStage | Format-Table -AutoSize
        }
    }

    "set-stock" {
        $Item = $Db.products | Where-Object { $_.sku -eq $Sku -or $_.id -eq $Sku }
        if (-not $Item) { Write-Error "SKU '$Sku' not found." }
        $Old = $Item.stock
        $Item.stock = [Math]::Max(0, $Stock)
        $Msg = "Set stock for $($Item.sku) ($($Item.name)) from $Old to $($Item.stock)."
        if ($Note) { $Msg += " Note: $Note" }
        Save-Database -LogMessage $Msg
        Write-Host "[OK] $Msg" -ForegroundColor Green
    }

    "restock" {
        $Item = $Db.products | Where-Object { $_.sku -eq $Sku -or $_.id -eq $Sku }
        if (-not $Item) { Write-Error "SKU '$Sku' not found." }
        $Old = $Item.stock
        $Item.stock = [Math]::Max(0, $Old + $Delta)
        $Sign = if ($Delta -ge 0) { "+$Delta" } else { "$Delta" }
        $Msg = "Adjusted stock for $($Item.sku) ($($Item.name)) by $Sign ($Old -> $($Item.stock))."
        if ($Note) { $Msg += " Note: $Note" }
        Save-Database -LogMessage $Msg
        Write-Host "[OK] $Msg" -ForegroundColor Green
    }

    "set-price" {
        $Item = $Db.products | Where-Object { $_.sku -eq $Sku -or $_.id -eq $Sku }
        if (-not $Item) { Write-Error "SKU '$Sku' not found." }
        $Old = $Item.price
        $Item.price = [Math]::Round($Price, 2)
        $Msg = "Updated price for $($Item.sku) ($($Item.name)) from `$$Old to `$$($Item.price)."
        Save-Database -LogMessage $Msg
        Write-Host "[OK] $Msg" -ForegroundColor Green
    }

    "update-rd" {
        $Item = $Db.products | Where-Object { $_.sku -eq $Sku -or $_.id -eq $Sku }
        if (-not $Item) { Write-Error "SKU '$Sku' not found." }
        $Old = $Item.rdStage
        $Item.rdStage = $Stage
        $Msg = "Updated In-House R&D Stage for $($Item.sku) from '$Old' to '$Stage'."
        if ($Note) { $Msg += " ($Note)" }
        Save-Database -LogMessage $Msg
        Write-Host "[OK] $Msg" -ForegroundColor Green
    }

    "add-product" {
        if (-not $Sku -or -not $Name) { Write-Error "-Sku and -Name are required for add-product." }
        $Existing = $Db.products | Where-Object { $_.sku -eq $Sku }
        if ($Existing) { Write-Error "SKU '$Sku' already exists." }

        $NewProd = [PSCustomObject]@{
            id          = "dn-" + ([Guid]::NewGuid().ToString().Substring(0, 6))
            sku         = $Sku
            name        = $Name
            category    = $Category
            price       = [Math]::Round($Price, 2)
            cost        = [Math]::Round($Cost, 2)
            stock       = $Stock
            reorderPoint= 10
            inHouse     = $true
            rdStage     = if ($Stage) { $Stage } else { "Stocked Inventory" }
            moldId      = "CUSTOM-SKU"
            curingSpec  = "Standard Spec"
            colorway    = if ($Colorway) { $Colorway } else { "Honey Gold & Obsidian" }
            image       = if ($Category -eq "Silicone Mats") { "assets/images/silicone-tray.png" } elseif ($Category -eq "Dabbing Tools") { "assets/images/dab-tools.png" } else { "assets/images/fluffy-blanket.png" }
            badge       = "New Release"
            featured    = $true
            description = if ($Description) { $Description } else { "New Dabnaps cozy release." }
            specs       = @("Designed by Dabnaps", "Cozy & Cloud-like edition")
        }
        $Db.products = @($Db.products) + @($NewProd)
        $Msg = "Added new SKU $Sku ($Name) at `$$Price with $Stock units."
        Save-Database -LogMessage $Msg
        Write-Host "[OK] $Msg" -ForegroundColor Green
    }

    "sync" {
        Save-Database -LogMessage ""
        Write-Host "[OK] Synced data\inventory.json to data\inventory-sync.js" -ForegroundColor Green
    }

    "reconcile-batch" {
        $TargetBatchId = if ($BatchId) { $BatchId } elseif ($Sku) { $Sku } else { "BATCH-2026-10B" }
        $Batch = $Db.inHouseProductionBatches | Where-Object { $_.batchId -eq $TargetBatchId }
        if (-not $Batch) { Write-Error "Batch '$TargetBatchId' not found." }

        $Item = $Db.products | Where-Object { $_.sku -eq $Batch.productSku }
        if (-not $Item) { Write-Error "Product SKU '$($Batch.productSku)' not found." }

        $OldStock = $Item.stock
        $CuredUnits = $Batch.unitsPassedQC
        $Item.stock = $OldStock + $CuredUnits
        $Item.rdStage = "Stocked Inventory"
        if ($Item.badge -eq "Low Stock") {
            $Item.badge = "In-House Engineered"
        }
        $Batch.stage = "Completed & Stocked"
        $Batch.notes = "$CuredUnits cured units reconciled into active stock."

        $Msg = "Reconciled $($Batch.batchId): Added $CuredUnits units of $($Item.sku) to stock ($OldStock -> $($Item.stock)). Batch marked Completed & Stocked."
        Save-Database -LogMessage $Msg
        Write-Host "[OK] $Msg" -ForegroundColor Green
    }
}
